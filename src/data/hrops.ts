export const letterSla = (r: LetterRequest): { tone: PfTone; label: string } => {
  if (r.state === "Issued") return { tone: "green", label: `Issued in ${r.hoursElapsed}h` };
  if (r.hoursElapsed >= 24) return { tone: "red", label: `${r.hoursElapsed}h — SLA breached` };
  if (r.hoursElapsed >= 18) return { tone: "yellow", label: `${24 - r.hoursElapsed}h left` };
  return { tone: "blue", label: `${24 - r.hoursElapsed}h left` };
};

