/** FR-088: outcomes reach the attrition model ONLY aggregated and permissioned. */
export const caseAggregate = () => {
  const open = DISCIPLINARY_CASES.filter((c) => c.stage !== "Closed").length;
  return {
    open, closed: DISCIPLINARY_CASES.length - open,
    byCategory: [...new Set(DISCIPLINARY_CASES.map((c) => c.category))].map((cat) => ({
      cat, n: DISCIPLINARY_CASES.filter((c) => c.category === cat).length,
    })),
    modelNote: "Only these counts reach the attrition feature set. No case narrative, no named subject, no sanction detail.",
  };
};
